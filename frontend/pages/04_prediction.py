"""Page 4 — Disease Prediction (all 3 models)"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import streamlit as st
import requests
import plotly.graph_objects as go

API_BASE = os.getenv("API_BASE_URL", "http://127.0.0.1:8000/api")

def get_headers():
    return {"Authorization": f"Bearer {st.session_state.get('token','')}",
            "Content-Type": "application/json"}

st.markdown("""
<div class="hg-header">
    <h1>🔬 Disease Risk Prediction</h1>
    <p>Enter your health parameters to receive AI-powered risk assessments</p>
</div>
""", unsafe_allow_html=True)

if not st.session_state.get("token"):
    st.warning("Error: Please log in first.")
    st.stop()

DISCLAIMER = """
<div class="disclaimer">
DISCLAMER: <strong>Important:</strong> These predictions are generated by Machine Learning models for
<strong>educational purposes only</strong>. They are NOT medical diagnoses. The model score shown
is a raw classifier probability and has NOT been clinically calibrated. Always consult a qualified
healthcare professional for medical advice.
</div>
"""

def render_result(result: dict, disease_name: str):
    risk = result.get("risk_category", "Unknown")
    score = result.get("model_score", 0)
    pred_class = result.get("predicted_class", 0)
    fi = result.get("feature_importance", {})
    recs = result.get("recommendations", [])
    model_name = result.get("best_model_name", "ML Model")
    pred_date = result.get("prediction_date","")

    color_map = {"Low": "#10b981", "Moderate": "#f59e0b", "High": "#ef4444"}
    color = color_map.get(risk, "#64748b")

    st.markdown(
    '<div class="disclaimer">'
    'This tool is for educational and informational purposes only. '
    'It is NOT a substitute for professional medical advice, diagnosis, or treatment. '
    'Always consult a qualified healthcare professional.'
    '</div>',
    unsafe_allow_html=True
)

    c1, c2, c3 = st.columns(3)
    with c1:
        st.metric("Risk Category", risk)
    with c2:
        st.metric("Model Score", f"{score:.2%}")
    with c3:
        st.metric("Prediction", "Positive" if pred_class == 1 else "Negative")

    # Gauge chart
    fig = go.Figure(go.Indicator(
        mode="gauge+number",
        value=round(score * 100, 1),
        title={"text": f"{disease_name} Risk Score (%)"},
        gauge={
            "axis": {"range": [0, 100]},
            "bar": {"color": color},
            "steps": [
                {"range": [0, 35],  "color": "#d1fae5"},
                {"range": [35, 65], "color": "#fef3c7"},
                {"range": [65, 100],"color": "#fee2e2"},
            ],
            "threshold": {"line": {"color": color, "width": 4}, "thickness": 0.75, "value": score*100},
        }
    ))
    fig.update_layout(height=280, margin=dict(l=20,r=20,t=40,b=20))
    st.plotly_chart(fig, use_container_width=True)

    if fi:
        st.markdown("#### 🔍 Feature Importance (Top Contributors)")
        sorted_fi = sorted(fi.items(), key=lambda x: -abs(x[1]))[:8]
        max_val = max(abs(v) for _, v in sorted_fi) or 1
        for feat, val in sorted_fi:
            pct = abs(val) / max_val
            st.markdown(f"""
            <div class="fi-bar-container">
                <span class="fi-label">{feat.replace('_',' ').title()}</span>
                <span class="fi-bar" style="width:{int(pct*220)}px;"></span>
                <span style="font-size:0.75rem;color:#64748b;margin-left:6px;">{val:.4f}</span>
            </div>
            """, unsafe_allow_html=True)

    st.markdown("#### Personalized Recommendations")

    for rec in recs[:-1]:
        st.markdown(
            f'<div class="rec-item">✅ {rec}</div>',
            unsafe_allow_html=True
        )

with st.container(key="prediction_tabs"):
    tab1, tab2, tab3 = st.tabs(["🩸 Diabetes", "❤️ Heart Disease", "🫀 Hypertension"])

# ── DIABETES ──────────────────────────────────────────────────────────────────
    with tab1:
        st.markdown("### 🩸 Diabetes Risk Prediction")
        st.caption("Based on the Pima Indians Diabetes Dataset (Smith et al., 1988)")
        st.markdown(DISCLAIMER, unsafe_allow_html=True)

        with st.form("diabetes_form"):
            c1, c2 = st.columns(2)
            with c1:
                preg     = st.number_input("Pregnancies", 0, 20, 1)
                glucose  = st.number_input("Glucose Level (mg/dL)", 0.0, 500.0, 120.0)
                bp       = st.number_input("Blood Pressure (mm Hg)", 0.0, 200.0, 70.0)
                skin     = st.number_input("Skin Thickness (mm)", 0.0, 100.0, 20.0)
            with c2:
                insulin  = st.number_input("Insulin (µU/mL)", 0.0, 900.0, 80.0)
                bmi      = st.number_input("BMI", 0.0, 70.0, 25.0)
                dpf      = st.number_input("Diabetes Pedigree Function", 0.0, 3.0, 0.5, step=0.01)
                age      = st.number_input("Age", 1, 120, 30)
            sub = st.form_submit_button("🔬 Predict Diabetes Risk", use_container_width=True)

        if sub:
            with st.spinner("Running diabetes model..."):
                r = requests.post(f"{API_BASE}/predict/diabetes",
                    json={"pregnancies": preg, "glucose": glucose, "blood_pressure": bp,
                          "skin_thickness": skin, "insulin": insulin, "bmi": bmi,
                          "diabetes_pedigree_function": dpf, "age": age},
                    headers=get_headers(), timeout=20)
            if r.ok:
                render_result(r.json(), "Diabetes")
            else:
                st.error(r.json().get("detail", "Prediction failed. Ensure models are trained."))

# ── HEART DISEASE ─────────────────────────────────────────────────────────────
    with tab2:
        st.markdown("### ❤️ Heart Disease Risk Prediction")
        st.caption("Based on UCI Heart Disease Dataset – Cleveland Clinic (Detrano et al., 1989)")
        st.markdown(DISCLAIMER, unsafe_allow_html=True)

        with st.form("heart_form"):
            c1, c2 = st.columns(2)
            with c1:
                age_h    = st.number_input("Age", 1, 120, 50, key="h_age")
                sex      = st.selectbox("Sex", ["Female (0)","Male (1)"])
                sex_v    = 0 if sex.startswith("Female") else 1
                cp       = st.selectbox("Chest Pain Type", ["Typical Angina (0)","Atypical Angina (1)","Non-Anginal Pain (2)","Asymptomatic (3)"])
                cp_v     = int(cp.split("(")[1][0])
                trestbps = st.number_input("Resting Blood Pressure (mm Hg)", 0.0, 250.0, 130.0)
                chol     = st.number_input("Serum Cholesterol (mg/dL)", 0.0, 600.0, 240.0)
                fbs      = st.selectbox("Fasting Blood Sugar > 120 mg/dL", ["No (0)","Yes (1)"])
                fbs_v    = int(fbs.split("(")[1][0])
            with c2:
                restecg  = st.selectbox("Resting ECG", ["Normal (0)","ST-T Wave Abnormality (1)","LV Hypertrophy (2)"])
                restecg_v= int(restecg.split("(")[1][0])
                thalach  = st.number_input("Max Heart Rate Achieved", 0.0, 250.0, 150.0)
                exang    = st.selectbox("Exercise-Induced Angina", ["No (0)","Yes (1)"])
                exang_v  = int(exang.split("(")[1][0])
                oldpeak  = st.number_input("ST Depression (oldpeak)", 0.0, 10.0, 1.0, step=0.1)
                slope    = st.selectbox("Slope of Peak Exercise ST", ["Upsloping (0)","Flat (1)","Downsloping (2)"])
                slope_v  = int(slope.split("(")[1][0])
                ca       = st.number_input("Major Vessels Colored by Fluoroscopy", 0, 4, 0)
                thal     = st.selectbox("Thalassemia", ["Normal (3)","Fixed Defect (6)","Reversible Defect (7)"])
                thal_v   = int(thal.split("(")[1].replace(")",""))
            sub_h = st.form_submit_button("🔬 Predict Heart Disease Risk", use_container_width=True)

        if sub_h:
            with st.spinner("Running heart disease model..."):
                r = requests.post(f"{API_BASE}/predict/heart",
                    json={"age": age_h, "sex": sex_v, "cp": cp_v, "trestbps": trestbps,
                        "chol": chol, "fbs": fbs_v, "restecg": restecg_v, "thalach": thalach,
                        "exang": exang_v, "oldpeak": oldpeak, "slope": slope_v,
                        "ca": ca, "thal": thal_v},
                    headers=get_headers(), timeout=20)
            if r.ok:
                render_result(r.json(), "Heart Disease")
            else:
                st.error(r.json().get("detail", "Prediction failed."))

    # ── HYPERTENSION ─────────────────────────────────────────────────────────────
    with tab3:
        st.markdown("### 🫀 Hypertension Risk Assessment")
        st.caption("Model trained on ACC/AHA guideline-based risk factor dataset")
        st.markdown(DISCLAIMER, unsafe_allow_html=True)

        with st.form("hyper_form"):
            c1, c2 = st.columns(2)
            with c1:
                age_hy  = st.number_input("Age", 1, 120, 40, key="hy_age")
                bmi_hy  = st.number_input("BMI", 10.0, 70.0, 26.0, key="hy_bmi")
                smoking_hy  = st.selectbox("Smoking Status", ["Non-smoker (0)","Smoker (1)"])
                smoking_v   = int(smoking_hy.split("(")[1][0])
                diabetes_hy = st.selectbox("Diabetes History", ["No (0)","Yes (1)"])
                diabetes_v  = int(diabetes_hy.split("(")[1][0])
            with c2:
                family_hy = st.selectbox("Family History of Hypertension", ["No (0)","Yes (1)"])
                family_v  = int(family_hy.split("(")[1][0])
                activity_hy = st.selectbox("Physical Activity", ["Low (0)","Moderate (1)","High (2)"])
                activity_v  = int(activity_hy.split("(")[1][0])
                salt_hy     = st.selectbox("Salt Intake", ["Low (0)","Moderate (1)","High (2)"])
                salt_v      = int(salt_hy.split("(")[1][0])
                alcohol_hy  = st.selectbox("Alcohol Intake", ["None (0)","Moderate (1)","Heavy (2)"])
                alcohol_v   = int(alcohol_hy.split("(")[1][0])
                stress_hy   = st.selectbox("Stress Level", ["Low (0)","Moderate (1)","High (2)"])
                stress_v    = int(stress_hy.split("(")[1][0])
            sub_hy = st.form_submit_button("🔬 Predict Hypertension Risk", use_container_width=True)

        if sub_hy:
            with st.spinner("Running hypertension model..."):
                r = requests.post(f"{API_BASE}/predict/hypertension",
                    json={"age": age_hy, "bmi": bmi_hy, "smoking": smoking_v,
                        "diabetes_history": diabetes_v, "family_history": family_v,
                        "physical_activity": activity_v, "salt_intake": salt_v,
                        "alcohol_intake": alcohol_v, "stress_level": stress_v},
                    headers=get_headers(), timeout=20)
            if r.ok:
                render_result(r.json(), "Hypertension")
            else:
                st.error(r.json().get("detail", "Prediction failed."))
